import AppDomain
import DataStructure
import Domain
import Foundation
import Testing

@Suite("Sample layouts")
struct SampleLayoutTests {
    /// Each sample's id derived from its key, so a key finds its sample again.
    static func id(for key: String) -> UUID {
        let hash = key.utf8.reduce(UInt64(0xCBF2_9CE4_8422_2325)) { ($0 ^ UInt64($1)) &* 0x100_0000_01B3 }
        let bytes = (0 ..< 16).map { UInt8(truncatingIfNeeded: hash >> (8 * ($0 % 8)) ^ UInt64($0)) }
        return UUID(uuid: (bytes[0], bytes[1], bytes[2], bytes[3], bytes[4], bytes[5], bytes[6], bytes[7],
                           bytes[8], bytes[9], bytes[10], bytes[11], bytes[12], bytes[13], bytes[14], bytes[15]))
    }

    static let samples = SeedDocuments.samples(idFor: id(for:))

    static func quality(_ document: ModelDocument) -> LayoutQuality {
        layoutQuality(of: document.model, positions: document.visuals.mapValues { (x: $0.x, y: $0.y) })
    }

    @Test(arguments: samples.map(\.name))
    func noCompartmentOverlapsAnotherAndNoLinkRunsUnderOne(name: String) throws {
        let document = try #require(Self.samples.first { $0.name == name })
        let quality = Self.quality(document)
        #expect(quality.overlaps == 0, "\(quality)")
        #expect(quality.linksUnderCompartments == 0, "\(quality)")
    }

    /// Up to ten compartments a layout without crossings exists, and the samples have one. The two
    /// large ICRP 137 models link a hub (plasma, blood) to nearly everything, which no straight-line
    /// drawing can do without crossings: their recorded counts are the bound.
    @Test(arguments: samples.map(\.name))
    func crossingsStayAtTheRecordedMinimum(name: String) throws {
        let document = try #require(Self.samples.first { $0.name == name })
        let bound = [Self.id(for: "icrp.u234.type.s"): 9, Self.id(for: "icrp.u238.chain"): 2][document.id] ?? 0
        #expect(Self.quality(document).crossings <= bound, "\(Self.quality(document))")
    }

    @Test func tidyLayoutIsReproducibleFromItsSeed() throws {
        let document = try #require(Self.samples.first { $0.id == Self.id(for: "icrp.sr90") })
        var first = SplitMix64(seed: 7), second = SplitMix64(seed: 7)
        let a = tidyLayout(of: document.model, attempts: 1).run(&first), b = tidyLayout(of: document.model, attempts: 1).run(&second)
        #expect(a.mapValues { [$0.x, $0.y] } == b.mapValues { [$0.x, $0.y] })
    }

    @Test func tidyLayoutUntanglesASmallModel() throws {
        let document = try #require(Self.samples.first { $0.id == Self.id(for: "icrp.pb210.po210") })
        var rng = SplitMix64(seed: SampleLayouts.seed)
        let quality = layoutQuality(of: document.model, positions: tidyLayout(of: document.model, attempts: 1).run(&rng))
        #expect(quality == LayoutQuality(overlaps: 0, crossings: 0, linksUnderCompartments: 0))
    }

    /// Regenerates `Sources/AppDomain/SampleLayouts.swift`. The large models take minutes unoptimised:
    /// `RECORD_SAMPLE_LAYOUTS=1 swift test -Xswiftc -O --filter recordSampleLayouts`
    @Test(.enabled(if: ProcessInfo.processInfo.environment["RECORD_SAMPLE_LAYOUTS"] != nil))
    func recordSampleLayouts() throws {
        let entries = try SampleLayouts.keys.map { key in
            let document = try #require(Self.samples.first { $0.id == Self.id(for: key) }, "no sample \(key)")
            var rng = SplitMix64(seed: SampleLayouts.seed)
            let positions = tidyLayout(of: document.model).run(&rng)
            let lines = document.model.compartments.compactMap { compartment in
                positions[compartment.id].map { "            \"\(compartment.id)\": (x: \(Int($0.x)), y: \(Int($0.y))),\n" }
            }
            return "        \"\(key)\": [\n" + lines.joined() + "        ],\n"
        }
        let source = """
        // Generated by SampleLayoutTests.recordSampleLayouts: `tidyLayout` run with
        // SplitMix64(seed: SampleLayouts.seed) on each sample listed in `SampleLayouts.keys`.
        // Don't edit by hand: change the list or the layout, then record again with
        // RECORD_SAMPLE_LAYOUTS=1 swift test -Xswiftc -O --filter recordSampleLayouts

        extension SampleLayouts {
            static let positions: [String: [String: (x: Double, y: Double)]] = [

        """ + entries.joined() + """
            ]
        }

        """
        let destination = URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent().deletingLastPathComponent()
            .appendingPathComponent("Sources/AppDomain/SampleLayouts+Generated.swift")
        try source.write(to: destination, atomically: true, encoding: .utf8)
    }
}
