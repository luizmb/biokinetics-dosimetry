// MARK: - Error

public enum ExportError: LocalizedError {
    case encodingFailed
    case pdfRequiresUIKit

    public var errorDescription: String? {
        switch self {
        case .encodingFailed:    "Could not encode data as UTF-8."
        case .pdfRequiresUIKit:  "PDF rendering requires UIKit (iOS/macOS)."
        }
    }
}
